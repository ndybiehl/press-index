export function originalMsrpCents(input: {
  kind: string;
  platformSlug: string;
  title: string;
  genre?: string;
}) {
  if (input.kind === "game") {
    const key = `${input.title}|${input.platformSlug}`;
    if (key in GAME_MSRP_OVERRIDES) return GAME_MSRP_OVERRIDES[key];
    return GAME_MSRP_BY_PLATFORM[input.platformSlug] ?? 4999;
  }
  if (input.kind === "system") {
    return SYSTEM_MSRP_BY_PLATFORM[input.platformSlug] ?? 19999;
  }
  return ACCESSORY_MSRP_BY_GENRE[input.genre ?? ""] ?? 2999;
}
